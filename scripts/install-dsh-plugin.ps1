param(
    [string]$Python = 'python',
    [ValidateSet('Bridge','Direct')][string]$Mode = 'Bridge',
    [string]$Profile = (Join-Path $env:USERPROFILE '.dsh\profiles\desktop'),
    [string]$Dsh = '',
    [switch]$Apply
)
$ErrorActionPreference = 'Stop'
$project = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot))
$package = Join-Path $project 'dsh-plugin'
$Profile = [IO.Path]::GetFullPath($Profile)
$profileParent = Split-Path -Parent $Profile
if ((Split-Path -Leaf $profileParent) -ne 'profiles') { throw 'Profile must be an existing DSH_HOME/profiles/<name> directory' }
$profileName = Split-Path -Leaf $Profile
$dshHome = Split-Path -Parent $profileParent
$patch = Join-Path $Profile 'cordis.patch.yml'
$manifest = Join-Path $Profile 'package.json'
foreach ($path in @($patch, $manifest, (Join-Path $package 'package.json'))) {
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "Missing required file: $path" }
}
$beforeManifest = Get-Content -LiteralPath $manifest -Raw -Encoding UTF8 | ConvertFrom-Json
$otherVersions = @{}
foreach ($dependency in $beforeManifest.dependencies.PSObject.Properties) {
    if ($dependency.Name -eq 'window-pilot-dsh') { continue }
    $dependencyFile = Join-Path (Join-Path (Join-Path $Profile 'node_modules') $dependency.Name) 'package.json'
    if (Test-Path -LiteralPath $dependencyFile -PathType Leaf) {
        $otherVersions[$dependency.Name] = (Get-Content -LiteralPath $dependencyFile -Raw -Encoding UTF8 | ConvertFrom-Json).version
    }
}
if (Test-Path -LiteralPath $Python -PathType Leaf) { $Python = (Resolve-Path -LiteralPath $Python).Path }
else { $Python = (Get-Command -Name $Python -CommandType Application -ErrorAction Stop).Source }
if (-not $Dsh) {
    $command = Get-Command dsh -CommandType Application -ErrorAction SilentlyContinue
    $Dsh = if ($command) { $command.Source } else { Join-Path $env:LOCALAPPDATA 'Programs\DeepSeek Harness\resources\runtime\cli\bin\dsh.cmd' }
}
if (-not (Test-Path -LiteralPath $Dsh -PathType Leaf)) { throw 'DSH CLI not found; pass -Dsh with its installed path' }
$Dsh = (Resolve-Path -LiteralPath $Dsh).Path
$config = Join-Path $project 'config.local.json'
$serviceFile = Join-Path $project '.local\admin-service\service.json'
if ($Mode -eq 'Bridge') {
    if (-not (Test-Path -LiteralPath $serviceFile -PathType Leaf)) { throw 'Install/review the administrator service first, or explicitly use -Mode Direct' }
    $service = Get-Content -LiteralPath $serviceFile -Raw -Encoding UTF8 | ConvertFrom-Json
    if ($service.project -ne $project -or $service.python -ne $Python) { throw 'Use the reviewed service project/Python; no profile changes' }
    $config = $service.config
}
if (-not (Test-Path -LiteralPath $config -PathType Leaf)) { throw 'Create/review config.local.json first' }
$bytes = [IO.File]::ReadAllBytes($patch)
$text = [Text.UTF8Encoding]::new($false,$true).GetString($bytes)
$matches = [regex]::Matches($text,'(?m)^(?<indent> *)- id: window-pilot-mcp *\r?$')
if ($matches.Count -gt 1) { throw 'Duplicate Window Pilot rows; inspect manually, no changes' }
$begin = $text.Length
$end = $begin
if ($matches.Count -eq 1) {
    $begin = $matches[0].Index
    $indent = $matches[0].Groups['indent'].Value.Length
    $end = $text.Length
    foreach ($candidate in [regex]::Matches($text.Substring($begin + $matches[0].Length),'(?m)^(?<indent> *)- ')) {
        if ($candidate.Groups['indent'].Value.Length -le $indent) { $end = $begin + $matches[0].Length + $candidate.Index; break }
    }
    $block = $text.Substring($begin,$end-$begin)
    if ($block -notmatch '(?m)^ *name: [''"]?(?:@deepseek-ai/dsh-mcp-client|window-pilot-dsh)[''"]? *\r?$') { throw 'Unexpected Window Pilot module; no changes' }
    if ($block -notmatch 'serverName: *window_pilot' -or $block -notmatch 'transport: *stdio') { throw 'Unexpected Window Pilot namespace/transport; no changes' }
    if ($indent -gt 0) {
        $parent = [regex]::Match($text.Substring(0,$begin),'(?m)^- insert: *\r?\n\z')
        $following = if ($end -lt $text.Length) { [regex]::Match($text.Substring($end),'^(?<indent> *)- ') } else { $null }
        if (-not $parent.Success -or ($following -and $following.Success -and $following.Groups['indent'].Value.Length -gt 0)) {
            throw 'Only the standalone legacy insert generated by this project can be migrated automatically; no changes'
        }
        $begin = $parent.Index
    }
} elseif ($text -match 'serverName: *window_pilot') { throw 'Window Pilot namespace already used by an unrecognized row; no changes' }
$arguments = if ($Mode -eq 'Bridge') { @('-m','window_pilot','bridge','--service-file',$serviceFile) } else { @('-m','window_pilot','serve','--config',$config) }
$commandJson = ConvertTo-Json -Compress $Python
$argsJson = ConvertTo-Json -Compress $arguments
$cwdJson = ConvertTo-Json -Compress $project
$sourceJson = ConvertTo-Json -Compress (Join-Path $project 'src')
$override = @"
- id: window-pilot-mcp
  name: window-pilot-dsh
  config:
    serverName: window_pilot
    transport: stdio
    command: $commandJson
    args: $argsJson
    cwd: $cwdJson
    env:
      PYTHONPATH: $sourceJson
      PYTHONUTF8: '1'
      PYTHONUNBUFFERED: '1'
    toolCallTimeoutMs: 30000
    failOnStartupError: false
"@
$updated = $text.Substring(0,$begin) + "`n" + $override + "`n" + $text.Substring($end)
if (-not $Apply) {
    [pscustomobject]@{preview_only=$true; package='window-pilot-dsh'; source="link:$package"; profile=$Profile;
        mode=$Mode; plugin='window-pilot-mcp'; namespace='window_pilot'; command=$Python; args=$arguments;
        changes='back up profile files; replace only Window Pilot insert with override; install/select local native bundle using official DSH CLI';
        service_lifecycle='unchanged; no UAC or administrator-task changes'} | ConvertTo-Json -Depth 5
    exit 0
}
if ($Mode -eq 'Bridge') {
    $probe = & $Python -I -S (Join-Path $PSScriptRoot 'runtime_entry.py') executor-status --service-file $serviceFile
    if ($LASTEXITCODE -ne 0) { throw 'Actual administrator service unavailable; profile unchanged' }
    $status = $probe | ConvertFrom-Json
    if (-not $status.health.executor.is_administrator -or $status.health.executor.mode -ne 'administrator_service') { throw 'Administrator executor not verified; profile unchanged' }
}
$backupDir = Join-Path $project ('.local\backups\native-plugin-' + (Get-Date -Format 'yyyyMMdd-HHmmss-fff'))
[IO.Directory]::CreateDirectory($backupDir) | Out-Null
foreach ($name in @('package.json','cordis.patch.yml','pnpm-lock.yaml','pnpm-workspace.yaml')) {
    $original = Join-Path $Profile $name
    if (Test-Path -LiteralPath $original -PathType Leaf) {
        $backup = Join-Path $backupDir $name
        [IO.File]::WriteAllBytes($backup,[IO.File]::ReadAllBytes($original))
        if ((Get-FileHash -LiteralPath $original).Hash -ne (Get-FileHash -LiteralPath $backup).Hash) { throw 'Backup mismatch; profile unchanged' }
    }
}
if ([Convert]::ToBase64String([IO.File]::ReadAllBytes($patch)) -ne [Convert]::ToBase64String($bytes)) { throw 'Profile patch changed concurrently; no write' }
$temporary = $patch + '.window-pilot-native.tmp'
[IO.File]::WriteAllText($temporary,$updated,[Text.UTF8Encoding]::new($false))
[IO.File]::Replace($temporary,$patch,[System.Management.Automation.Language.NullString]::Value)
$oldDshHome = [Environment]::GetEnvironmentVariable('DSH_HOME','Process')
try {
    [Environment]::SetEnvironmentVariable('DSH_HOME',$dshHome,'Process')
    & $Dsh plugin --profile $profileName add --save-prod --ignore-scripts --prefer-offline "link:$package"
    if ($LASTEXITCODE -ne 0) { throw "DSH CLI installation failed; verified backup retained at $backupDir; inspect state before retrying" }
} catch {
    if ([IO.File]::ReadAllText($patch) -eq $updated) {
        [IO.File]::WriteAllBytes($temporary,$bytes)
        [IO.File]::Replace($temporary,$patch,[System.Management.Automation.Language.NullString]::Value)
        Write-Warning 'Restored only the Window Pilot profile patch after failed installation; verified backups retained.'
    } else { Write-Warning 'Profile changed concurrently; not overwriting it. Inspect the verified backup and current state.' }
    throw
} finally { [Environment]::SetEnvironmentVariable('DSH_HOME',$oldDshHome,'Process') }
$installed = Get-Content -LiteralPath $manifest -Raw -Encoding UTF8 | ConvertFrom-Json
if (-not $installed.dependencies.'window-pilot-dsh' -or $installed.dsh.profile.bundles -notcontains 'window-pilot-dsh') { throw 'DSH did not record the native bundle; inspect installation before retrying' }
foreach ($dependency in $beforeManifest.dependencies.PSObject.Properties) {
    if ($dependency.Name -eq 'window-pilot-dsh') { continue }
    if ($installed.dependencies.($dependency.Name) -ne $dependency.Value) { throw "Unrelated dependency spec changed: $($dependency.Name); inspect verified backup" }
    if ($otherVersions.ContainsKey($dependency.Name)) {
        $dependencyFile = Join-Path (Join-Path (Join-Path $Profile 'node_modules') $dependency.Name) 'package.json'
        $actualVersion = (Get-Content -LiteralPath $dependencyFile -Raw -Encoding UTF8 | ConvertFrom-Json).version
        if ($actualVersion -ne $otherVersions[$dependency.Name]) { throw "Unrelated plugin version changed: $($dependency.Name); inspect verified backup" }
    }
}
Write-Output "Installed native Window Pilot bundle. Backup: $backupDir"
Write-Output 'Save your DSH work, then close and reopen DSH desktop to load the changed bundle graph. Page refresh alone did not load this external CLI install on DSH 0.2.1-rc.3.'
Write-Output 'Open Plugins and verify the Window Pilot card, actual loaded status and tools; old tokens/frames do not survive reconnection.'
Write-Output 'The card switch controls MCP tools only. The administrator service and its task were not changed.'
